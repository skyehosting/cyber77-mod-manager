'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
const on = channel => cb => {
  const listener = (_e, payload) => cb(payload);
  ipcRenderer.on(channel, listener);
  return () => ipcRenderer.removeListener(channel, listener);
};

contextBridge.exposeInMainWorld('api', {
  snapshot: () => call('snapshot'),
  logs: () => call('logs'),
  getSettings: () => call('settings:get'),
  setSettings: patch => call('settings:set', patch),
  validateKey: () => call('settings:validateKey'),
  detectGame: () => call('settings:detectGame'),
  pickFolder: title => call('dialog:folder', title),
  pickFile: (title, filters) => call('dialog:file', title, filters),
  addLinks: text => call('links:add', text),
  planLinks: text => call('links:plan', text),
  queuePlan: (token, deps, files) => call('links:queue', token, deps, files),
  gameInstalls: () => call('game:installs'),
  launchGame: () => call('game:launch'),
  exportJson: (kind, data) => call('export:json', kind, data),
  openVortex: () => call('vortex:open'),
  checkUpdates: () => call('updates:check'),
  updateMods: ids => call('updates:apply', ids),
  repair: ids => call('mods:repair', ids),
  switchProfile: id => call('profiles:switch', id),
  createProfile: (name, copyCurrent) => call('profiles:create', name, copyCurrent),
  renameProfile: (id, name) => call('profiles:rename', id, name),
  deleteProfile: id => call('profiles:delete', id),
  exportProfile: id => call('profiles:export', id),
  importProfilePlan: () => call('profiles:importPlan'),
  importProfileApply: (token, name) => call('profiles:importApply', token, name),
  importProfileCancel: token => call('profiles:importCancel', token),
  revealExport: () => call('profiles:revealExport'),
  cancelJob: id => call('jobs:cancel', id),
  retryJob: id => call('jobs:retry', id),
  clearJobs: () => call('jobs:clear'),
  install: keys => call('downloads:install', keys),
  installAndEnable: keys => call('downloads:installAndEnable', keys),
  deleteDownloads: keys => call('downloads:delete', keys),
  importArchives: () => call('downloads:import'),
  enable: ids => call('mods:enable', ids),
  disable: ids => call('mods:disable', ids),
  uninstall: ids => call('mods:uninstall', ids),
  reinstall: ids => call('mods:reinstall', ids),
  prioritize: ids => call('mods:prioritize', ids),
  modFiles: id => call('mods:files', id),
  modConflicts: id => call('mods:conflicts', id),
  redeploy: () => call('mods:redeploy'),
  purge: () => call('mods:purge'),
  fomodSubmit: (token, selections) => call('fomod:submit', token, selections),
  fomodCancel: token => call('fomod:cancel', token),
  openPath: which => call('open:path', which),
  openNexus: (game, modId) => call('open:nexus', game, modId),
  reportError: msg => ipcRenderer.send('renderer-error', String(msg)),
  onSnapshot: on('snapshot'),
  onJob: on('job'),
  onLog: on('log'),
  onFomod: on('fomod'),
  onToast: on('toast'),
  gameLogSnapshot: () => call('gamelog:snapshot'),
  gameLogSources: () => call('gamelog:sources'),
  revealGameFile: rel => call('gamelog:reveal', rel),
  openGameFile: rel => call('gamelog:open', rel),
  onGameLog: on('gamelog'),
  onGameLogReset: on('gamelog-reset'),
  onGameStatus: on('gamestatus'),
});
