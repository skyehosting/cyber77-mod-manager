/**
 * A global MO2 instance for Cyberpunk ("Night City"), with its data in another folder (base_directory),
 * plus a Skyrim instance that must be ignored and a portable one added as a user folder.
 * Mods: Alpha and Beta both ship shared.archive (MO2 gives it to Beta, higher in modlist.txt),
 * CET Framework keeps its loader in root/, Gamma is off, "Unlisted" is in no modlist.txt.
 */
function makeMo2(root) {
  const local = path.join(root, 'local');
  const inst = path.join(local, 'ModOrganizer', 'Night City');
  const base = path.join(root, 'mo2data');
  write(path.join(inst, 'ModOrganizer.ini'), [
    '[General]', 'gameName=Cyberpunk 2077', `gamePath=@ByteArray(${path.join(root, 'game').replace(/\\/g, '\\\\')})`, 'selected_profile=@ByteArray(Main)',
    '[Settings]', `base_directory=${base.replace(/\\/g, '\\\\')}`, 'profiles_directory=%BASE_DIR%/profiles',
  ].join('\r\n'));
  write(path.join(local, 'ModOrganizer', 'Skyrim', 'ModOrganizer.ini'), '[General]\r\ngameName=Skyrim Special Edition\r\n');
  const mod = (name, files, meta) => {
    for (const [rel, text] of Object.entries(files)) write(path.join(base, 'mods', name, rel), text);
    if (meta) write(path.join(base, 'mods', name, 'meta.ini'), meta);
  };
  mod('Alpha', { 'archive/pc/mod/alpha.archive': 'A', 'archive/pc/mod/shared.archive': 'from alpha' },
    '[General]\r\nmodid=10\r\nversion=1.0\r\ninstallationFile=Alpha-10-1-0.zip\r\nnexusFileStatus=1\r\n[installedFiles]\r\n1\\modid=10\r\n1\\fileid=100\r\nsize=1\r\n');
  mod('Beta', { 'archive/pc/mod/beta.archive': 'B', 'archive/pc/mod/shared.archive': 'from beta' },
    '[General]\r\nmodid=20\r\nversion=2.1\r\nnexusFileStatus=3\r\n[installedFiles]\r\nsize=0\r\n');
  mod('CET Framework', { 'root/bin/x64/version.dll': 'cet loader', 'bin/x64/plugins/cyber_engine_tweaks/mods/Thing/init.lua': 'lua', 'bin/x64/plugins/cyber_engine_tweaks/mods/Thing/settings.json': '{"a":1}' },
    '[General]\r\nmodid=107\r\nversion=1.35\r\n[installedFiles]\r\n1\\modid=107\r\n1\\fileid=700\r\nsize=1\r\n');
  mod('Gamma', { 'r6/scripts/Gamma/g.reds': 'G' }, '[General]\r\nmodid=30\r\nversion=3\r\n');
  mod('Unlisted', { 'archive/pc/mod/u.archive': 'U' }, null);
  mod('Visuals_separator', {}, '[General]\r\ncolor=@Variant(\\0)\r\n');
  // MO2's own workaround (Cyberpunk plugin 3.x) and a mod with no files: both stay in MO2.
  mod('disable CrashReporter (MO CET fix)', { 'bin/x64/CrashReporter/CrashReporter.exe': '' }, null);
  mod('Empty Mod', {}, '[General]\r\nmodid=55\r\n');
  mod('Alpha backup', { 'archive/pc/mod/alpha.archive': 'old' }, null);
  // Beta's file id is only in its download's .meta.
  write(path.join(base, 'downloads', 'Alpha-10-1-0.zip'), 'zip of alpha');
  write(path.join(base, 'downloads', 'Alpha-10-1-0.zip.meta'), '[General]\r\nmodID=10\r\nfileID=100\r\nmodName=Alpha Mod\r\n');
  const beta = path.join(root, 'elsewhere', 'Beta-20-2-1.7z');
  write(beta, 'zip of beta');
  write(`${beta}.meta`, '[General]\r\nmodID=20\r\nfileID=200\r\nmodName=Beta Mod\r\n');
  write(path.join(base, 'mods', 'Beta', 'meta.ini'), `[General]\r\nmodid=20\r\nversion=2.1\r\nnexusFileStatus=3\r\ninstallationFile=${beta.replace(/\\/g, '\\\\')}\r\n`);
  const header = '# This file was automatically generated by Mod Organizer.\r\n';
  write(path.join(base, 'profiles', 'Main', 'modlist.txt'), `${header}+Beta\r\n+CET Framework\r\n-Visuals_separator\r\n+Alpha\r\n-Gamma\r\n+Gone\r\n`);
  write(path.join(base, 'profiles', 'Nothing', 'modlist.txt'), `${header}-Alpha\r\n`);
  write(path.join(base, 'profiles', 'Photo', 'modlist.txt'), `${header}+Gamma\r\n+Alpha\r\n-Beta\r\n`);
  // A portable MO2 the user added by hand.
  const portable = path.join(root, 'PortableMO2');
  write(path.join(portable, 'ModOrganizer.exe'), 'exe');
  write(path.join(portable, 'ModOrganizer.ini'), '[General]\r\ngameName=cyberpunk 2077\r\n');
  write(path.join(portable, 'profiles', 'Default', 'modlist.txt'), header);
  return { local, base, portable };
}

/** Every file under a folder with its content hash: MO2's data must not change at all. */
function fingerprint(dir) {
  const out = {};
  const walk = d => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const f = path.join(d, e.name);
      if (e.isDirectory()) walk(f);
      else out[path.relative(dir, f)] = crypto.createHash('sha1').update(fs.readFileSync(f)).digest('hex');
    }
  };
  walk(dir);
  return out;
}

test('reading MO2: Cyberpunk instances only, profiles in priority order, Nexus ids, root/ files', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cmm-mo2-'));
  const { local, portable } = makeMo2(root);
  const bridge = new Mo2Bridge({ log: quiet, localAppData: local, scan: false, extraFolders: () => [portable] });
  const { found, instances } = bridge.read();
  assert.ok(found);
  assert.deepStrictEqual(instances.map(i => [i.name, i.portable]).sort(), [['Night City', false], ['Portable (PortableMO2)', true]]);
  const nc = instances.find(i => i.name === 'Night City');
  assert.strictEqual(nc.gamePath, path.join(root, 'game'));
  assert.deepStrictEqual([...nc.mods.keys()].sort(), ['Alpha', 'Beta', 'CET Framework', 'Empty Mod', 'Gamma', 'Unlisted', 'disable CrashReporter (MO CET fix)'], 'separators and backups are not mods');
  assert.ok([...nc.mods.values()].every(m => !m.filesCache), 'file lists are read only when needed');

  const main = nc.profiles.find(p => p.name === 'Main');
  assert.ok(main.selected);
  assert.deepStrictEqual(main.order.slice(-4), ['Beta', 'CET Framework', 'Alpha', 'Gamma'], 'listed ones in modlist order, missing folders dropped');
  assert.deepStrictEqual(main.order.slice(0, -4).sort(), ['Empty Mod', 'Unlisted', 'disable CrashReporter (MO CET fix)'], 'unlisted ones first (highest)');
  assert.deepStrictEqual(main.enabled, ['Beta', 'CET Framework', 'Alpha']);
  assert.deepStrictEqual(nc.profiles.find(p => p.name === 'Photo').enabled, ['Gamma', 'Alpha']);

  const alpha = nc.mods.get('Alpha');
  assert.deepStrictEqual([alpha.modId, alpha.fileId, alpha.version, alpha.modName, alpha.category], [10, 100, '1.0', 'Alpha Mod', 'MAIN']);
  assert.ok(alpha.archive.endsWith('Alpha-10-1-0.zip'));
  const beta = nc.mods.get('Beta');
  assert.deepStrictEqual([beta.modId, beta.fileId, beta.category, beta.modName], [20, 200, 'OPTIONAL', 'Beta Mod'], "the file id from the download's .meta");
  const cet = nc.mods.get('CET Framework');
  assert.ok(bridge.modFiles(cet).some(f => f.dest === 'bin\\x64\\version.dll'), 'root/ goes to the game root');
  assert.strictEqual(bridge.skipReason(cet), '');
  assert.match(bridge.skipReason(nc.mods.get('disable CrashReporter (MO CET fix)')), /CrashReporter/);
  assert.match(bridge.skipReason(nc.mods.get('Empty Mod')), /no files/);
  assert.strictEqual(nc.mods.get('Unlisted').modId, 0);
});

function setupManager() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cmm-mo2m-'));
  const game = path.join(root, 'game');
  write(path.join(game, 'bin', 'x64', 'Cyberpunk2077.exe'), 'exe');
  const { local, base } = makeMo2(root);
  const before = process.env.CMM_MO2_LOCALAPPDATA;
  process.env.CMM_MO2_LOCALAPPDATA = local;
  const settings = new Settings(path.join(root, 'ud'), null);
  settings.update({ gamePath: game });
  const mgr = new ModManager({ settings, log: quiet });
  process.env.CMM_MO2_LOCALAPPDATA = before;
  const inst = mgr.mo2.read().instances.find(i => i.name === 'Night City');
  return { mgr, game, base, inst, settings };
}

test('moving MO2 mods in: linked files, Nexus ids, MO2 order, archives; MO2 itself untouched', async () => {
  const { mgr, base, inst, settings } = setupManager();
  const untouched = fingerprint(base);
  const view = mgr.mo2View();
  assert.deepStrictEqual(view.instances.map(i => [i.name, i.mods, i.here, i.left]), [['Night City', 7, 0, 7]]);

  const r = await mgr.adoptFromMo2(inst.id, 'all');
  assert.deepStrictEqual([r.adopted.length, r.skipped, r.failed], [5, 2, 0], 'the workaround and the empty mod stay in MO2, quietly');
  assert.deepStrictEqual(fingerprint(base), untouched, 'nothing in the MO2 instance changed');

  const mods = Object.values(mgr.data.mods);
  const by = name => mods.find(m => m.name === name);
  assert.ok(mods.every(m => !m.enabled), 'moved mods start switched off');
  assert.deepStrictEqual([by('Alpha').id, by('Alpha').modId, by('Alpha').fileId, by('Alpha').version], ['100', 10, 100, '1.0']);
  // Linked, not copied: the staged file is MO2's file.
  const staged = path.join(settings.stagingDir, by('Alpha').id, 'archive', 'pc', 'mod', 'alpha.archive');
  assert.strictEqual(fs.statSync(staged).ino, fs.statSync(path.join(base, 'mods', 'Alpha', 'archive', 'pc', 'mod', 'alpha.archive')).ino);
  assert.ok(by('CET Framework').files.includes('bin/x64/version.dll'));
  // MO2's order: Beta was above Alpha in modlist.txt, so it has the higher priority here.
  assert.ok(by('Beta').priority > by('Alpha').priority && by('Unlisted').priority > by('Beta').priority);
  assert.ok(fs.existsSync(mgr.data.downloads[by('Alpha').id].path), 'its archive came along');
  assert.deepStrictEqual([mgr.mo2View().instances[0].here, mgr.mo2View().instances[0].left], [5, 0], 'nothing left to bring');
  // A settings file is copied, not linked: the game rewriting it here never changes MO2's copy.
  const json = 'bin/x64/plugins/cyber_engine_tweaks/mods/Thing/settings.json'.split('/');
  const stagedJson = path.join(settings.stagingDir, by('CET Framework').id, ...json);
  assert.notStrictEqual(fs.statSync(stagedJson).ino, fs.statSync(path.join(base, 'mods', 'CET Framework', ...json)).ino);
  assert.strictEqual(fs.readFileSync(stagedJson, 'utf8'), '{"a":1}');

  // Again: nothing new.
  const again = await mgr.adoptFromMo2(inst.id, 'all');
  assert.ok(again.adopted.every(a => a.matched));
  assert.strictEqual(Object.keys(mgr.data.mods).length, 5);
});

test('"Use here" refuses an empty MO2 profile and a missing game folder, before changing anything', async () => {
  const { mgr, settings } = setupManager();
  const profiles = mgr.mo2View().instances[0].profiles;
  await assert.rejects(mgr.useMo2Profile(profiles.find(p => p.name === 'Nothing').id), /no mods enabled/);
  settings.update({ gamePath: path.join(os.tmpdir(), 'no-such-game') });
  await assert.rejects(mgr.useMo2Profile(profiles.find(p => p.name === 'Main').id), /Cyberpunk 2077 folder/);
  assert.strictEqual(Object.keys(mgr.data.mods).length, 0, 'nothing was brought over');
  assert.ok(!Object.values(mgr.data.profiles.list).some(p => p.fromMo2), 'no profile was made');
});

test('a mod already installed here (same Nexus file) is matched, not added twice', async () => {
  const { mgr, inst } = setupManager();
  mgr.data.mods['100'] = { id: '100', key: '100', name: 'ArchiveXL-ish', modId: 10, fileId: 100, files: [], enabled: true, priority: mgr.data.nextPriority++ };
  const r = await mgr.adoptFromMo2(inst.id, ['Alpha']);
  assert.deepStrictEqual(r.adopted, [{ folder: 'Alpha', id: '100', matched: true }]);
  assert.strictEqual(Object.keys(mgr.data.mods).length, 1);
});

test('"Use here": a profile with exactly the MO2 profile\'s mods, in its order, deployed; again updates it', async () => {
  const { mgr, game, base } = setupManager();
  const untouched = fingerprint(base);
  const pid = mgr.mo2View().instances[0].profiles.find(p => p.name === 'Main').id;
  const plan = mgr.mo2ProfilePlan(pid);
  assert.deepStrictEqual([plan.mods, plan.here, plan.move, plan.profile], [3, 0, 3, '']);
  assert.deepStrictEqual(mgr.mo2ProfileMods(pid).map(m => m.name), ['Alpha', 'CET Framework', 'Beta'], "MO2's window order: the last wins");

  const r = await mgr.useMo2Profile(pid);
  assert.strictEqual(r.name, 'Main (MO2)');
  assert.strictEqual(mgr.data.profiles.active, r.id);
  const on = Object.values(mgr.data.mods).filter(m => m.enabled).map(m => m.name).sort();
  assert.deepStrictEqual(on, ['Alpha', 'Beta', 'CET Framework']);
  // A settings file in the game, rewritten there, leaves MO2's copy alone.
  fs.writeFileSync(path.join(game, 'bin', 'x64', 'plugins', 'cyber_engine_tweaks', 'mods', 'Thing', 'settings.json'), '{"a":2}');
  assert.deepStrictEqual(fingerprint(base), untouched, 'MO2 unchanged after the game wrote a setting');
  // In the game: Beta's shared.archive won, as in MO2; CET's loader is at the game root.
  assert.strictEqual(fs.readFileSync(path.join(game, 'archive', 'pc', 'mod', 'shared.archive'), 'utf8'), 'from beta');
  assert.strictEqual(fs.readFileSync(path.join(game, 'bin', 'x64', 'version.dll'), 'utf8'), 'cet loader');
  assert.ok(!fs.existsSync(path.join(game, 'r6', 'scripts', 'Gamma')), 'Gamma is off in that profile');
  assert.deepStrictEqual(fingerprint(base), untouched, 'MO2 unchanged');

  // The Photo profile, then Main again: the same profile here is updated, not a second one.
  const photo = mgr.mo2View().instances[0].profiles.find(p => p.name === 'Photo').id;
  await mgr.useMo2Profile(photo);
  assert.ok(fs.existsSync(path.join(game, 'r6', 'scripts', 'Gamma', 'g.reds')));
  const again = await mgr.useMo2Profile(pid);
  assert.strictEqual(again.id, r.id);
  assert.strictEqual(Object.values(mgr.data.profiles.list).filter(p => p.fromMo2).length, 2);
  assert.strictEqual(mgr.mo2View().instances[0].profiles.find(p => p.name === 'Main').profile, 'Main (MO2)');
});
